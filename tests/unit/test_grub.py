class GrubCfgFacts(unittest.TestCase):
    """test reading kernel facts from a grub.cfg generated by grub2-mkconfig"""

    def check(self, grub_default, saved_entry, default_index):
        kernels = grub.get_grub_cfg_facts(GRUB_CFG, grub_default, saved_entry)
        self.assertEqual(["0", "1", "2", "3", "4"], [k["index"] for k in kernels])
        self.assertEqual([default_index], [k["index"] for k in kernels if k["default"]])
        return kernels

    def test_entries(self):
        kernels = self.check("0", None, "0")
        self.assertEqual(
            {
                "args": "rw quiet console=ttyS0,115200",
                "default": True,
                "id": "gnulinux-simple-11f1",
                "index": "0",
                "initrd": "/boot/initrd-6.12.0-47-default",
                "kernel": "/boot/vmlinuz-6.12.0-47-default",
                "root": "UUID=11f1",
                "title": "SLES 16.1",
            },
            kernels[0],
        )
        self.assertEqual(
            "gnulinux-advanced-11f1>gnulinux-40-advanced", kernels[3]["id"]
        )
        self.assertEqual("single", kernels[2]["args"])
        self.assertEqual("Custom", kernels[4]["id"])

    def test_default(self):
        self.check(None, None, "0")
        self.check("1", None, "1")
        self.check("1>2", None, "3")
        self.check("saved", None, "0")
        self.check("saved", "gnulinux-advanced-11f1>gnulinux-40-advanced", "3")
        self.check(
            "Advanced options for SLES 16.1>SLES 16.1, with Linux 6.12.0-40-default",
            None,
            "3",
        )
        self.check("3", None, "4")

    def test_shell_vars(self):
        text = 'GRUB_DEFAULT=0\nGRUB_CMDLINE_LINUX_DEFAULT="rw quiet"\nGRUB_CMDLINE_LINUX=""\n'
        self.assertEqual("0", grub.get_shell_var(text, "GRUB_DEFAULT"))
        self.assertEqual(
            "rw quiet", grub.get_shell_var(text, "GRUB_CMDLINE_LINUX_DEFAULT")
        )
        self.assertEqual("", grub.get_shell_var(text, "GRUB_CMDLINE_LINUX"))
        self.assertIsNone(grub.get_shell_var(text, "GRUB_TIMEOUT"))
        with self.assertRaises(ValueError):
            grub.get_shell_var('X="$X quiet"\n', "X")
        self.assertEqual(
            '# comment\nGRUB_DEFAULT="saved"\nGRUB_TIMEOUT=1\n',
            grub.set_shell_var(
                "# comment\nGRUB_DEFAULT=0\nGRUB_TIMEOUT=1\n", "GRUB_DEFAULT", "saved"
            ),
        )
        self.assertEqual('X=1\nY="2"\n', grub.set_shell_var("X=1\n", "Y", "2"))
        self.assertEqual(
            {"saved_entry": "1"},
            grub.get_grubenv("# GRUB Environment Block\nsaved_entry=1\n####"),
        )

    def test_shell_vars_tuned(self):
        tuned = (
            'GRUB_CMDLINE_LINUX_DEFAULT="${GRUB_CMDLINE_LINUX_DEFAULT:+'
            '$GRUB_CMDLINE_LINUX_DEFAULT }\\$tuned_params"'
        )
        name = "GRUB_CMDLINE_LINUX_DEFAULT"
        text = 'GRUB_CMDLINE_LINUX_DEFAULT="quiet"\n' + tuned + "\n"
        self.assertEqual("quiet", grub.get_shell_var(text, name))
        self.assertIsNone(grub.get_shell_var(tuned + "\n", name))
        edited = grub.set_shell_var(text, name, "quiet audit=1")
        self.assertEqual(
            'GRUB_CMDLINE_LINUX_DEFAULT="quiet audit=1"\n' + tuned + "\n", edited
        )
        self.assertEqual("quiet audit=1", grub.get_shell_var(edited, name))
        self.assertEqual(
            'X=1\nGRUB_CMDLINE_LINUX_DEFAULT="audit=1"\n' + tuned + "\n",
            grub.set_shell_var("X=1\n" + tuned + "\n", name, "audit=1"),
        )
        later = tuned + '\nGRUB_CMDLINE_LINUX_DEFAULT="a"\n'
        self.assertEqual(
            tuned + '\nGRUB_CMDLINE_LINUX_DEFAULT="a b"\n',
            grub.set_shell_var(later, name, "a b"),
        )
        with self.assertRaises(ValueError):
            grub.get_shell_var(text.replace("tuned_params", "other_params"), name)


class RunningSystem(unittest.TestCase):
    """test what the pbl backend reads from the running system"""

    def test_check_loader(self):
        module = MagicMock()
        module.fail_json.side_effect = SystemExit
        for loader in ["grub2", "grub2-efi"]:
            module.run_command.return_value = (0, loader + "\n", "")
            grub.check_loader(module)
        for loader in ["systemd-boot", "grub2-bls", "none"]:
            module.run_command.return_value = (0, loader + "\n", "")
            with self.assertRaises(SystemExit):
                grub.check_loader(module)

    def test_separate_boot(self):
        """Paths in grub.cfg are relative to a separate /boot"""
        grub_cfg = (
            "menuentry 'SLES 16.1' $menuentry_id_option 'simple' {\n"
            "    linux /vmlinuz-1 root=UUID=1 quiet\n"
            "    initrd /ucode.img /initrd-1\n"
            "}\n"
        )

        def read_file(path):
            return grub_cfg if path == grub.GRUB_CFG else ""

        with patch.object(grub, "read_file", side_effect=read_file):
            with patch.object(grub.os.path, "ismount", return_value=True):
                kernels = grub.get_kernels(MagicMock(), False)
        self.assertEqual("/boot/vmlinuz-1", kernels[0]["kernel"])
        self.assertEqual("/boot/ucode.img /boot/initrd-1", kernels[0]["initrd"])

    def test_next_boot_root(self):
        """A transactional system reads the snapshot that it boots next"""
        output = {
            "findmnt": "ro,relatime,seclabel,subvolid=268,subvol=/@/.snapshots/2/snapshot\n",
            "btrfs": "ID 271 gen 96 top level 265 path @/.snapshots/5/snapshot\n",
        }
        module = MagicMock()
        module.run_command.side_effect = lambda cmd: (0, output[cmd[0]], "")
        self.assertEqual("/", grub.get_next_boot_root(module, False))
        with patch.object(grub.os.path, "isdir", return_value=False):
            self.assertEqual("/", grub.get_next_boot_root(module, True))
        with patch.object(grub.os.path, "isdir", return_value=True):
            self.assertEqual(
                "/.snapshots/5/snapshot", grub.get_next_boot_root(module, True)
            )
            output["btrfs"] = output["btrfs"].replace("/5/", "/2/")
            self.assertEqual("/", grub.get_next_boot_root(module, True))


class WriteFile(unittest.TestCase):
    """test how the pbl backend writes a file that has a mode"""

    def setUp(self):
        workdir = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, workdir)
        self.path = os.path.join(workdir, "01_password")
        self.modes = []
        self.module = MagicMock()
        self.module.atomic_move.side_effect = self.atomic_move

    def atomic_move(self, src, dest):
        """Like AnsibleModule.atomic_move: the mode of the replaced file, or the default"""
        created = not os.path.exists(dest)
        if not created:
            shutil.copymode(dest, src)
        os.rename(src, dest)
        if created:
            umask = os.umask(0)
            os.umask(umask)
            os.chmod(dest, 0o666 & ~umask)
        self.modes.append(self.mode(dest))

    def mode(self, path):
        return os.stat(path).st_mode & 0o777

    def test_mode(self):
        """A file written with a mode never has a wider one"""
        grub.write_file(self.module, self.path, "new\n", 0o700)
        self.assertEqual(0o700, self.mode(self.path))
        os.chmod(self.path, 0o755)
        grub.write_file(self.module, self.path, "replaced\n", 0o700)
        self.assertEqual([0o600, 0o700], self.modes)
        self.assertEqual(0o700, self.mode(self.path))
