"""Read and write the GRUB configuration that grub2-mkconfig generates, as on SUSE"""

from __future__ import absolute_import, division, print_function

__metaclass__ = type

import os
import re
import shlex
import tempfile

GRUB_CFG = "/boot/grub2/grub.cfg"
GRUBENV = "/boot/grub2/grubenv"
DEFAULT_GRUB = "/etc/default/grub"
PASSWORD_SCRIPT = "/etc/grub.d/01_password"
LOADERS = ["grub2", "grub2-efi"]
TRANSACTIONAL_UPDATE = ["transactional-update", "--continue", "--non-interactive"]

MENU_HEADER = re.compile(r"\s*(menuentry|submenu)\s+(['\"])(.*?)\2(.*)\{\s*$")
MENU_ID = re.compile(r"\$menuentry_id_option\s+['\"]([^'\"]*)['\"]")


def get_shell_var(text, name):
    """Get the value of the last NAME= assignment in a shell variables file"""
    value = None
    for line in text.splitlines():
        match = re.match(r"\s*" + name + r"=(.*)$", line)
        if match:
            if re.search(r"[$`\\]", match.group(1)):
                raise ValueError("%s uses shell expansion or escapes" % name)
            value = " ".join(shlex.split(match.group(1), comments=True))
    return value


def set_shell_var(text, name, value):
    """Set NAME="value" in a shell variables file, replacing its last assignment"""
    new_line = '%s="%s"' % (name, value)
    lines = text.splitlines()
    for i in reversed(range(len(lines))):
        if re.match(r"\s*" + name + r"=", lines[i]):
            lines[i] = new_line
            break
    else:
        lines.append(new_line)
    return "\n".join(lines) + "\n"


def get_grubenv(text):
    """Get the variables of a GRUB environment block"""
    grubenv = {}
    for line in text.splitlines():
        if line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        grubenv[key] = value
    return grubenv


def get_default_entry(kernels, grub_default, saved_entry):
    """Get the index of the entry that GRUB boots by default"""
    target = grub_default or "0"
    if target == "saved":
        target = saved_entry or "0"
    for kernel in kernels:
        if re.match(r"^\d+(>\d+)?$", target):
            if kernel["menu_index"] == target or (
                ">" not in target and kernel["menu_index"].split(">")[0] == target
            ):
                return kernel["index"]
        elif target in (kernel["id"], kernel["title"], kernel["menu_title"]):
            return kernel["index"]
    return None


def get_grub_cfg_facts(grub_cfg, grub_default, saved_entry):
    """Get kernel facts from a grub.cfg generated by grub2-mkconfig"""
    kernels = []
    blocks = []
    entry = {}
    top_index = -1
    sub_index = -1
    for line in grub_cfg.splitlines():
        stripped = line.strip()
        header = MENU_HEADER.match(line)
        submenus = [b for b in blocks if isinstance(b, dict)]
        if header:
            menu_id = MENU_ID.search(header.group(4))
            item = {
                "title": header.group(3),
                "id": menu_id.group(1) if menu_id else header.group(3),
            }
            if not submenus and not entry:
                top_index += 1
                sub_index = -1
                item["menu_index"] = str(top_index)
            else:
                sub_index += 1
                item["menu_index"] = "%d>%d" % (top_index, sub_index)
            if submenus:
                item["menu_title"] = submenus[-1]["title"] + ">" + item["title"]
                item["id"] = submenus[-1]["id"] + ">" + item["id"]
            else:
                item["menu_title"] = item["title"]
            if header.group(1) == "submenu":
                blocks.append(item)
            else:
                entry = item
                blocks.append("entry")
        elif stripped.endswith("{"):
            blocks.append("other")
        elif stripped == "}" and blocks:
            block = blocks.pop()
            if block == "entry":
                if "kernel" in entry:
                    entry["index"] = str(len(kernels))
                    kernels.append(entry)
                entry = {}
        elif entry and stripped.split(" ")[0].split("\t")[0] in ("linux", "linuxefi"):
            words = stripped.split()
            entry["kernel"] = words[1]
            entry["root"] = ""
            args = []
            for word in words[2:]:
                if word.startswith("root="):
                    entry["root"] = word.split("=", 1)[1]
                else:
                    args.append(word)
            entry["args"] = " ".join(args)
        elif entry and stripped.split(" ")[0].split("\t")[0] in ("initrd", "initrdefi"):
            entry["initrd"] = " ".join(stripped.split()[1:])
    default_index = get_default_entry(kernels, grub_default, saved_entry)
    for kernel in kernels:
        kernel["default"] = kernel["index"] == default_index
        del kernel["menu_index"]
        del kernel["menu_title"]
    return kernels


def read_file(path):
    """Read a text file, or return an empty string when it does not exist"""
    if not os.path.exists(path):
        return ""
    with open(path) as f:
        return f.read()


def write_file(module, path, content, mode=None):
    """Replace a file's content, keeping its ownership, mode and SELinux context"""
    tmpfd, tmpfile = tempfile.mkstemp(dir=os.path.dirname(path))
    try:
        with os.fdopen(tmpfd, "w") as f:
            f.write(content)
        if mode is None:
            module.atomic_move(tmpfile, path)
            return
        # atomic_move keeps the mode of the file it replaces, or of a link's target, and
        # gives a new file the default, so narrow the file and drop a link first
        if os.path.islink(path):
            os.unlink(path)
        elif os.path.exists(path):
            os.chmod(path, os.stat(path).st_mode & mode)
        umask = os.umask(0o077)
        try:
            module.atomic_move(tmpfile, path)
        finally:
            os.umask(umask)
        os.chmod(path, mode)
    finally:
        if os.path.exists(tmpfile):
            os.unlink(tmpfile)


def check_loader(module):
    """Fail unless pbl reports a boot loader configured by grub2-mkconfig"""
    rc, loader, stderr = module.run_command(["pbl", "--show"])
    loader = loader.strip()
    if rc != 0 or loader not in LOADERS:
        module.fail_json(
            msg="Boot loader '%s' is not supported on this platform, supported are: %s %s"
            % (loader, ", ".join(LOADERS), stderr.strip())
        )


def get_next_boot_root(module, transactional):
    """Get the root of the snapshot that the next boot uses on a transactional system"""
    if not transactional:
        return "/"
    _unused, mount_options, _unused = module.run_command(
        ["findmnt", "-no", "OPTIONS", "/"]
    )
    _unused, default, _unused = module.run_command(
        ["btrfs", "subvolume", "get-default", "/"]
    )
    booted = re.search(r"subvol=/?([^,\s]+)", mount_options)
    pending = re.search(r" path @/(\S+)", default)
    if booted and pending and booted.group(1) != "@/" + pending.group(1):
        root = "/" + pending.group(1)
        if os.path.isdir(os.path.join(root, "boot/grub2")):
            return root
    return "/"


def next_boot_path(root, path):
    """Get a path inside the snapshot that the next boot uses"""
    return os.path.join(root, path.lstrip("/"))


def get_kernels(module, transactional):
    """Get kernel facts for the configuration that the next boot uses"""
    root = get_next_boot_root(module, transactional)
    try:
        grub_default = get_shell_var(read_file(DEFAULT_GRUB), "GRUB_DEFAULT")
    except ValueError as e:
        module.fail_json(msg="Cannot parse %s: %s" % (DEFAULT_GRUB, e))
    saved_entry = get_grubenv(read_file(next_boot_path(root, GRUBENV))).get(
        "saved_entry"
    )
    kernels = get_grub_cfg_facts(
        read_file(next_boot_path(root, GRUB_CFG)), grub_default, saved_entry
    )
    if os.path.ismount("/boot"):
        for kernel in kernels:
            for key in ["kernel", "initrd"]:
                if key in kernel:
                    kernel[key] = " ".join(
                        path if path.startswith("/boot/") else "/boot" + path
                        for path in kernel[key].split()
                    )
    return kernels
